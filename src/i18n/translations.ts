// WhatsApp Link Generator Helper
export function generateWhatsAppLink(params: {
  phone?: string;
  language: Language;
  productName?: string;
  price?: number;
  quantity?: number;
  cartItems?: { name: string; price: number; quantity: number }[];
  customerName?: string;
  wilaya?: string;
  address?: string;
  orderId?: string;
  deliveryType?: 'home' | 'desk';
  total?: number;
}): string {
  const targetNumber = '213696544855';
  let message = '';

  if (params.orderId) {
    // Order confirmation message
    if (params.language === 'ar') {
      message = `مرحباً Products Global Dz، قمت بطلب جديد عبر الموقع:\n` +
        `رقم الطلب: ${params.orderId}\n` +
        `الاسم: ${params.customerName || ''}\n` +
        `الولاية: ${params.wilaya || ''}\n` +
        `العنوان: ${params.address || ''}\n` +
        `المبلغ الإجمالي: ${params.total || 0} د.ج (الدفع عند الاستلام)\n` +
        `يرجى تأكيد الشحن في أقرب وقت. شكراً!`;
    } else if (params.language === 'en') {
      message = `Hello Products Global Dz, I just placed an order on the website:\n` +
        `Order ID: ${params.orderId}\n` +
        `Name: ${params.customerName || ''}\n` +
        `Wilaya: ${params.wilaya || ''}\n` +
        `Address: ${params.address || ''}\n` +
        `Total: ${params.total || 0} DZD (Cash on Delivery)\n` +
        `Please confirm shipping. Thank you!`;
    } else {
      // Default French
      message = `Bonjour Products Global Dz, je viens de passer une commande sur votre boutique :\n` +
        `N° Commande : ${params.orderId}\n` +
        `Nom : ${params.customerName || ''}\n` +
        `Wilaya : ${params.wilaya || ''}\n` +
        `Adresse : ${params.address || ''}\n` +
        `Total à payer : ${params.total || 0} DA (Paiement à la livraison)\n` +
        `Merci de confirmer l'expédition !`;
    }
  } else if (params.cartItems && params.cartItems.length > 0) {
    // Multiple cart items
    if (params.language === 'ar') {
      message = `مرحباً Products Global Dz، أود طلب هذه المنتجات من سلة التسوق:\n\n` +
        params.cartItems.map((item, idx) => `${idx + 1}. ${item.name} (${item.quantity}x) - ${item.price * item.quantity} د.ج`).join('\n') +
        `\n\nالمجموع: ${params.total || ''} د.ج\n` +
        (params.wilaya ? `الولاية: ${params.wilaya}\n` : '') +
        `يرجى تأكيد التوفر وموعد الشحن.`;
    } else if (params.language === 'en') {
      message = `Hello Products Global Dz, I want to order these items from my cart:\n\n` +
        params.cartItems.map((item, idx) => `${idx + 1}. ${item.name} (${item.quantity}x) - ${item.price * item.quantity} DZD`).join('\n') +
        `\n\nTotal: ${params.total || ''} DZD\n` +
        (params.wilaya ? `Wilaya: ${params.wilaya}\n` : '') +
        `Please confirm availability and shipping.`;
    } else {
      message = `Bonjour Products Global Dz, je souhaite commander ces articles de mon panier :\n\n` +
        params.cartItems.map((item, idx) => `${idx + 1}. ${item.name} (${item.quantity}x) - ${item.price * item.quantity} DA`).join('\n') +
        `\n\nTotal : ${params.total || ''} DA\n` +
        (params.wilaya ? `Wilaya : ${params.wilaya}\n` : '') +
        `Merci de m'indiquer la disponibilité et les modalités de livraison.`;
    }
  } else if (params.productName) {
    // Single product order
    const qty = params.quantity || 1;
    if (params.language === 'ar') {
      message = `مرحباً Products Global Dz، أود طلب المنتج التالي:\n` +
        `المنتج: ${params.productName}\n` +
        `السعر: ${params.price} د.ج\n` +
        `الكمية: ${qty}\n` +
        `المجموع: ${(params.price || 0) * qty} د.ج\n` +
        `يرجى إفادتي بمعلومات التوصيل لولايتي. شكراً!`;
    } else if (params.language === 'en') {
      message = `Hello Products Global Dz, I would like to order this item:\n` +
        `Product: ${params.productName}\n` +
        `Price: ${params.price} DZD\n` +
        `Quantity: ${qty}\n` +
        `Total: ${(params.price || 0) * qty} DZD\n` +
        `Please let me know the delivery details for my wilaya. Thank you!`;
    } else {
      message = `Bonjour Products Global Dz, je souhaite commander cet article :\n` +
        `Produit : ${params.productName}\n` +
        `Prix : ${params.price} DA\n` +
        `Quantité : ${qty}\n` +
        `Total : ${(params.price || 0) * qty} DA\n` +
        `Merci de me communiquer les détails de livraison pour ma wilaya !`;
    }
  } else {
    // General chat
    if (params.language === 'ar') {
      message = `مرحباً Products Global Dz، أود الاستفسار عن منتجاتكم وخدمة التوصيل.`;
    } else if (params.language === 'en') {
      message = `Hello Products Global Dz, I would like more information about your products and delivery in Algeria.`;
    } else {
      message = `Bonjour Products Global Dz, j'aimerais avoir plus de renseignements sur vos produits et la livraison en Algérie.`;
    }
  }

  return `https://wa.me/${targetNumber}?text=${encodeURIComponent(message)}`;
}
